"""Measure College Scorecard coverage for the v2 go/no-go decision.

Reads the raw Scorecard CSVs as data only (stdlib csv, no eval) and prints a
markdown report: schools in scope, and how many bachelor's programs have
earnings and debt that are not privacy-suppressed.

Usage:
    python3 -I scripts/scorecard_coverage.py data/raw/scorecard > docs/data_coverage.md
"""

from __future__ import annotations

import csv
import sys
from collections import Counter, defaultdict
from pathlib import Path

csv.field_size_limit(sys.maxsize)

STATES_50_DC = set(
    "AL AK AZ AR CA CO CT DE DC FL GA HI ID IL IN IA KS KY LA ME MD MA MI MN MS MO MT NE "
    "NV NH NJ NM NY NC ND OH OK OR PA RI SC SD TN TX UT VT VA WA WV WI WY".split()
)
CONTROL = {"1": "Public", "2": "Private nonprofit", "3": "Private for-profit"}
BACHELORS = "3"  # CREDLEV / HIGHDEG code for bachelor's
EARN_COLS = ["EARN_MDN_1YR", "EARN_MDN_4YR", "EARN_MDN_5YR"]
DEBT_COL = "DEBT_ALL_STGP_EVAL_MDN"


def num(v: str | None) -> float | None:
    """Parse a Scorecard cell; NULL / PrivacySuppressed / blanks become None."""
    if v is None:
        return None
    v = v.strip()
    if not v or v.upper() in {"NULL", "NA", "PS", "PRIVACYSUPPRESSED"}:
        return None
    try:
        return float(v)
    except ValueError:
        return None


def size_bucket(ugds: float | None) -> str:
    if ugds is None:
        return "unknown"
    if ugds < 2_000:
        return "small (<2k)"
    if ugds < 10_000:
        return "medium (2k-10k)"
    return "large (10k+)"


def pct(a: float, b: float) -> str:
    return f"{(100 * a / b):.1f}%" if b else "n/a"


def main(raw_dir: Path) -> None:
    inst_path = raw_dir / "Most-Recent-Cohorts-Institution.csv"
    fos_path = raw_dir / "Most-Recent-Cohorts-Field-of-Study.csv"

    # --- institutions -------------------------------------------------------
    inst: dict[str, dict[str, str]] = {}
    with inst_path.open(newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            inst[row["UNITID"]] = row

    # --- bachelor's programs (field of study) -------------------------------
    bach_rows: list[dict[str, str]] = []
    units_with_bach_program: set[str] = set()
    suppressed_markers: Counter[str] = Counter()
    with fos_path.open(newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            if row["CREDLEV"] != BACHELORS:
                continue
            bach_rows.append(row)
            units_with_bach_program.add(row["UNITID"])
            raw = row.get("EARN_MDN_4YR", "").strip()
            if num(raw) is None:
                suppressed_markers[raw or "<blank>"] += 1

    # --- scope ----------------------------------------------------------------
    def in_scope(uid: str, row: dict[str, str], states: set[str] | None) -> bool:
        if row.get("CURROPER") != "1":
            return False
        if states is not None and row.get("STABBR") not in states:
            return False
        # Must actually offer a bachelor's program. HIGHDEG >= 3 alone admits ~270
        # graduate-only schools (law, medicine, theology), so it is not used.
        return uid in units_with_bach_program

    scope_all = {u for u, r in inst.items() if in_scope(u, r, None)}
    scope = {u for u, r in inst.items() if in_scope(u, r, STATES_50_DC)}
    grad_only = {
        u for u, r in inst.items()
        if r.get("CURROPER") == "1" and r.get("STABBR") in STATES_50_DC
        and (num(r.get("HIGHDEG")) or 0) >= 3 and u not in units_with_bach_program
    }

    programs = [r for r in bach_rows if r["UNITID"] in scope]
    n_prog = len(programs)
    cip4s = {r["CIPCODE"] for r in programs}

    def weight(r: dict[str, str]) -> float:
        return (num(r.get("IPEDSCOUNT1")) or 0) + (num(r.get("IPEDSCOUNT2")) or 0)

    total_w = sum(weight(r) for r in programs)

    out: list[str] = []
    w = out.append
    w("# Scorecard data coverage (phase 2 go/no-go)\n")
    w("Generated by `scripts/scorecard_coverage.py` from Scorecard files released 2026-10-15 "
      "(field of study) and 2026-11-02 (institution).\n")

    w("## Schools in scope\n")
    w("Rule: currently operating, in the 50 states or DC, and offers at least one bachelor's "
      "program in the field-of-study file.\n")
    w("| Set | Schools |\n|---|---|")
    w(f"| All institutions in file | {len(inst):,} |")
    w(f"| In scope, incl. territories | {len(scope_all):,} |")
    w(f"| **In scope, 50 states + DC** | **{len(scope):,}** |")
    by_control = Counter(CONTROL.get(inst[u]["CONTROL"], "?") for u in scope)
    for k, v in sorted(by_control.items()):
        w(f"| &nbsp;&nbsp;{k} | {v:,} |")
    w(f"| Excluded: degree-granting but no bachelor's programs (mostly graduate-only) | {len(grad_only):,} |")
    w("")

    w("## Admission signal (for Safety / Target / Reach)\n")
    def has(r: dict[str, str], c: str) -> bool:
        return num(r.get(c)) is not None
    n_scope = len(scope)
    adm = sum(1 for u in scope if has(inst[u], "ADM_RATE"))
    open_adm = sum(1 for u in scope if inst[u].get("OPENADMP") == "1")
    either = sum(1 for u in scope if has(inst[u], "ADM_RATE") or inst[u].get("OPENADMP") == "1")
    tests = sum(1 for u in scope if has(inst[u], "SATMT25") or has(inst[u], "ACTCM25"))
    sel = sum(1 for u in scope if (num(inst[u].get("ADM_RATE")) or 1) < 0.15)
    w("| Signal | Schools | Coverage |\n|---|---|---|")
    w(f"| Admission rate reported | {adm:,} | {pct(adm, n_scope)} |")
    w(f"| Open admission (`OPENADMP`=1) | {open_adm:,} | {pct(open_adm, n_scope)} |")
    w(f"| **Admission rate or open admission** | **{either:,}** | **{pct(either, n_scope)}** |")
    w(f"| SAT or ACT 25th–75th range | {tests:,} | {pct(tests, n_scope)} |")
    w(f"| Admission rate under 15% (always Reach) | {sel:,} | {pct(sel, n_scope)} |")
    w("")

    w("## School-level fields (in-scope schools)\n")
    w("| Field | Non-null | Coverage |\n|---|---|---|")
    def npt_any(r: dict[str, str], suffix: str) -> float | None:
        return num(r.get(f"NPT4{suffix}_PUB")) or num(r.get(f"NPT4{suffix}_PRIV"))
    checks = {
        "Admission rate (ADM_RATE)": lambda r: num(r.get("ADM_RATE")),
        "SAT math 25th (SATMT25)": lambda r: num(r.get("SATMT25")),
        "ACT composite 25th (ACTCM25)": lambda r: num(r.get("ACTCM25")),
        "Avg net price (NPT4)": lambda r: npt_any(r, ""),
        "Net price, $0-30k bracket": lambda r: npt_any(r, "1"),
        "Net price, $110k+ bracket": lambda r: npt_any(r, "5"),
        "Completion rate (C150_4)": lambda r: num(r.get("C150_4")),
        "School median earnings 10yr": lambda r: num(r.get("MD_EARN_WNE_P10")),
        "School median debt": lambda r: num(r.get("GRAD_DEBT_MDN")),
        "Lat/long": lambda r: num(r.get("LATITUDE")),
    }
    for label, fn in checks.items():
        k = sum(1 for u in scope if fn(inst[u]) is not None)
        w(f"| {label} | {k:,} | {pct(k, len(scope))} |")
    w("")

    w("## Bachelor's programs (school x major, CIP 4-digit)\n")
    w(f"- Programs in scope: **{n_prog:,}** across **{len(cip4s):,}** distinct majors (CIP codes)")
    w(f"- Graduates represented (IPEDS completions, weights below): {int(total_w):,}\n")
    w("| Field | Programs with data | Unweighted | Weighted by graduates |\n|---|---|---|---|")
    for col in EARN_COLS + [DEBT_COL]:
        have = [r for r in programs if num(r.get(col)) is not None]
        hw = sum(weight(r) for r in have)
        w(f"| `{col}` | {len(have):,} | {pct(len(have), n_prog)} | {pct(hw, total_w)} |")
    any_earn = [r for r in programs if any(num(r.get(c)) is not None for c in EARN_COLS)]
    w(f"| any earnings horizon | {len(any_earn):,} | {pct(len(any_earn), n_prog)} | "
      f"{pct(sum(weight(r) for r in any_earn), total_w)} |")
    w("")

    w("### Earnings coverage (`EARN_MDN_4YR`) by school type and size\n")
    w("| Group | Programs | With earnings | Coverage |\n|---|---|---|---|")
    groups: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for r in programs:
        has = num(r.get("EARN_MDN_4YR")) is not None
        ir = inst[r["UNITID"]]
        for g in (CONTROL.get(ir["CONTROL"], "?"), size_bucket(num(ir.get("UGDS")))):
            groups[g][0] += 1
            groups[g][1] += has
    for g, (t, h) in sorted(groups.items()):
        w(f"| {g} | {t:,} | {h:,} | {pct(h, t)} |")
    w("")

    w("### Schools with at least one bachelor's program reporting earnings\n")
    units_with_earn = {r["UNITID"] for r in programs if num(r.get("EARN_MDN_4YR")) is not None}
    w(f"{len(units_with_earn):,} of {len(scope):,} in-scope schools ({pct(len(units_with_earn), len(scope))}).\n")

    w("### Raw values seen where `EARN_MDN_4YR` is missing (all bachelor's rows)\n")
    w("| Value | Rows |\n|---|---|")
    for v, c in suppressed_markers.most_common(5):
        w(f"| `{v}` | {c:,} |")
    w("")

    # --- decision -------------------------------------------------------------
    best_col, best_cov = max(
        ((c, sum(1 for r in programs if num(r.get(c)) is not None) / n_prog) for c in EARN_COLS),
        key=lambda t: t[1],
    )
    best_w = sum(weight(r) for r in programs if num(r.get(best_col)) is not None) / total_w
    w("## Decision\n")
    w(f"Best earnings horizon: `{best_col}` — {best_cov:.1%} of programs, {best_w:.1%} of graduates.\n")
    w("Pre-registered rule (docs/SPEC.md §5): ≥ 40% of programs with earnings → by-major earnings is the "
      "headline; otherwise lead with school-wide earnings and show by-major where available.\n")
    verdict = "GO — by-major earnings is the headline" if best_cov >= 0.40 else \
        "FALLBACK — lead with school-wide earnings; by-major where available"
    w(f"**Verdict (unweighted rule): {verdict}.**\n")
    w("The rule was set before looking at the data and is kept as written. Missing programs are "
      "mostly small ones (privacy suppression), so graduate-weighted coverage is much higher: "
      f"{best_w:.0%} of bachelor's graduates are in a program with `{best_col}`. The product shows "
      "by-major earnings wherever they exist and falls back to school-wide earnings, labelled, "
      "everywhere else. Horizons are not mixed: one horizon is used throughout so numbers compare.")

    print("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "data/raw/scorecard"))
